//! Skill learner: draft a skill from a successful session.

/// Learned skills must be approved before they are written or used. The
/// session runner owns the write path and must gate it behind explicit user
/// approval; this flag documents that contract from the skill side.
pub const REQUIRES_APPROVAL: bool = true;

/// Max characters kept per prompt/result section in a learned skill.
const MAX_SECTION_CHARS: usize = 2000;

/// Draft a skill name from a successful prompt.
pub fn draft_name(prompt: &str) -> String {
    let words: Vec<String> = prompt
        .to_lowercase()
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty() && *w != "the")
        .take(3)
        .map(str::to_string)
        .collect();
    let slug = if words.is_empty() {
        "workflow".to_string()
    } else {
        words.join("-")
    };
    format!("auto-{slug}")
}

/// Render a learned SKILL.md from a successful session transcript.
/// The name is slugified (path traversal and CRLF cannot survive) and a
/// leading frontmatter block is stripped from the prompt/result so the
/// generated file keeps exactly one frontmatter block. Control characters
/// are stripped, secrets are redacted, and each section is capped at
/// `MAX_SECTION_CHARS`. The output carries `freedas/needs-review: true` so
/// callers/UI can require approval even after the file exists.
pub fn render_skill(name: &str, prompt: &str, result: &str) -> String {
    let safe_name = slugify_skill_name(name);
    let prompt = truncate_chars(
        &freedas_core::redact::redact(&strip_controls(strip_leading_frontmatter(prompt))),
        MAX_SECTION_CHARS,
    );
    let result = truncate_chars(
        &freedas_core::redact::redact(&strip_controls(strip_leading_frontmatter(result))),
        MAX_SECTION_CHARS,
    );
    format!(
        "---\nname: {safe_name}\ndescription: Learned workflow from a successful session\nmetadata:\n  freedas/autogenerated: true\n  freedas/needs-review: true\n---\n\n## Workflow\n\nLast successful prompt: {prompt}\n\nResult: {result}\n"
    )
}

fn strip_controls(s: &str) -> String {
    s.chars()
        .filter(|&c| c == '\n' || c == '\t' || !c.is_control())
        .collect()
}

fn truncate_chars(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    let mut out: String = s.chars().take(max).collect();
    out.push_str("\n…[truncated]");
    out
}

fn slugify_skill_name(name: &str) -> String {
    let mut out = String::new();
    let mut prev_dash = true;
    for c in name.to_lowercase().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
            prev_dash = false;
        } else if (c == '-' || c == '_' || c == ' ' || c == '/' || c == '.')
            && !out.is_empty()
            && !prev_dash
        {
            out.push('-');
            prev_dash = true;
        }
        if out.len() >= 64 {
            break;
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    if out.is_empty() {
        "auto-workflow".to_string()
    } else {
        out
    }
}

fn strip_leading_frontmatter(s: &str) -> &str {
    let t = s.strip_prefix("\u{FEFF}").unwrap_or(s);
    let rest = t
        .strip_prefix("---\r\n")
        .or_else(|| t.strip_prefix("---\n"))
        .or_else(|| t.strip_prefix("---"));
    let Some(rest) = rest else {
        return s;
    };
    let Some((_, after)) = rest.split_once("\n---") else {
        return s;
    };
    after.trim_start_matches(['\n', '\r'])
}
